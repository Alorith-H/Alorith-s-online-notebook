/* 由6爻（自下而上，true=阳）查卦 */
function lookupGua(lines) {
  var lower = '', upper = '';
  for (var i = 0; i < 3; i++) lower += lines[i] ? '1' : '0';
  for (var j = 3; j < 6; j++) upper += lines[j] ? '1' : '0';
  var ui = TRIGRAM_ORDER.indexOf(upper), li = TRIGRAM_ORDER.indexOf(lower);
  var g = GUA64[ui][li];
  return { name: g[0], guaCi: g[1], upper: TRIGRAMS[upper], lower: TRIGRAMS[li] };
}

/* 变卦：动爻阴阳互换 */
function changedLines(lines, moving) {
  var out = lines.slice();
  for (var k = 0; k < moving.length; k++) out[moving[k]] = !out[moving[k]];
  return out;
}

/* 爻名：如 初九 / 六二 / 上六 */
function yaoName(idx, yang) {
  var posName = ['初','二','三','四','五','上'][idx];
  var numName = ['一','二','三','四','五'][idx];
  if (idx === 0) return yang ? '初九' : '初六';
  if (idx === 5) return yang ? '上九' : '上六';
  return (yang ? '九' : '六') + numName;
}
